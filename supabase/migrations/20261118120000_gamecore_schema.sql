-- A community's projects, numbered 1, 2, 3, ... A row is written once, when the project
-- starts (required actions are frozen then). Progress is never stored: it is counted
-- from the append-only action log (compute-on-read, §20.3 #2).
create table gamecore.projects (
  id uuid primary key default gen_random_uuid(),
  community_id uuid not null references gamecore.communities (id),
  seq integer not null check (seq >= 1),
  kind text not null references gamecore.project_catalog (kind),
  title text not null,
  level integer not null check (level >= 1),
  required_actions integer not null check (required_actions >= 1),
  started_on date not null,
  unique (community_id, seq)
);
alter table gamecore.projects enable row level security;

-- Append-only action log. The id is generated by the client, so retries are idempotent (§20.3b #4).
-- The daily limit is enforced by the database itself: each action takes one of the
-- three energy slots of its Calgary day, and a slot can be used once.
create table gamecore.actions (
  id uuid primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  community_id uuid not null references gamecore.communities (id),
  project_id uuid not null references gamecore.projects (id),
  calgary_day date not null,
  energy_slot smallint not null check (energy_slot between 1 and 3),
  created_at timestamptz not null default now(),
  unique (user_id, calgary_day, energy_slot)
);
alter table gamecore.actions enable row level security;
create index actions_project_day_idx on gamecore.actions (project_id, calgary_day);
create index actions_community_day_idx on gamecore.actions (community_id, calgary_day);

-- Append-only: actions are never updated (deletes only cascade from account deletion).
create function gamecore.actions_append_only()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  raise exception 'gamecore.actions is append-only' using errcode = '42501';
end;
$$;

create trigger actions_no_update
before update on gamecore.actions
for each row execute function gamecore.actions_append_only();

revoke all on all tables in schema gamecore from public, anon, authenticated;
revoke all on all functions in schema gamecore from public;
