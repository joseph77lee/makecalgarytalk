-- Module: gamecore — communities, players, projects and actions (requirement.md §7.7, §8, §20.3b).
--
-- Tables live in the `gamecore` schema, which the API does not expose. Every table has
-- Row Level Security enabled with NO policies: the only way in is through the
-- `public.gamecore_*` functions (security definer), which enforce the game rules.

create schema if not exists gamecore;
revoke all on schema gamecore from public;

-- Calgary communities (reference data, seeded from City of Calgary Open Data).
create table gamecore.communities (
  id uuid primary key default gen_random_uuid(),
  -- Per-city data (§20.5): a new city adds rows with its own `city`.
  city text not null default 'calgary',
  -- City community code, e.g. 'MAH' (stable; names can change).
  code text not null,
  official_name text not null,
  name text not null,
  sector text,
  -- Residents (2021 federal census, or latest civic census); null for brand-new communities.
  population integer check (population >= 0),
  population_year smallint,
  unique (city, code)
);
alter table gamecore.communities enable row level security;

-- A player and the community they currently belong to.
-- TEMPORARY until Residency (M7): the community is chosen manually (no location check).
create table gamecore.players (
  user_id uuid primary key references auth.users (id) on delete cascade,
  community_id uuid not null references gamecore.communities (id),
  -- Calgary day the player joined this community (stands in for the verification day until M7).
  joined_on date not null
);
alter table gamecore.players enable row level security;
create index players_community_idx on gamecore.players (community_id);

-- Project templates. Projects cycle through the catalog in `position` order; each full
-- cycle raises the level and the required actions (requirement.md §7.7, §22.8: starting values).
create table gamecore.project_catalog (
  position smallint primary key check (position >= 1),
  kind text not null unique,
  title text not null
);
alter table gamecore.project_catalog enable row level security;

