#!/usr/bin/env python3
"""
Writes the gamecore build map seed migration from supabase/data/build_map.json and
supabase/data/community_personas.csv (requirement.md v1.48 §7.6, §7.9).

  python3 -I supabase/data/build_map_seed.py supabase/migrations/<timestamp>_gamecore_build_map_seed.sql

Step conditions (residents, streak days, stage multiplier) come from build_map.json `conditions`:
community and nature steps 1-6 use `common`, later decoration steps add no condition; persona steps
1-3 use `common`, persona steps 4-6 are the landmarks (`landmarks` by order, stage 6). Rows are
upserted and steps no longer in the map are deleted, so a later change is a new migration
generated the same way (after launch: never delete a step that has projects).
"""
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOP_STAGE = 6


def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def conditions(step, doc):
    """(stage, residents, streak days) of one step."""
    common = {c["step"]: c for c in doc["conditions"]["common"]}
    landmarks = {c["order"]: c for c in doc["conditions"]["landmarks"]}
    track, n = step["track"], step["step"]
    if track == "root":
        return 0, 0, 0
    if track == "persona" and n >= 4:
        c = landmarks[n - 3]
        return TOP_STAGE, c.get("residents", 0), c.get("streakDays", 0)
    if n in common:
        c = common[n]
        return min(n, TOP_STAGE), c.get("residents", 0), c.get("streakDays", 0)
    return TOP_STAGE, 0, 0  # endless decoration: no new condition


def main(out):
    doc = json.loads((HERE / "build_map.json").read_text())
    steps = doc["steps"]
    keys = [s["key"] for s in steps]
    assert len(keys) == len(set(keys)), "duplicate step keys"
    rows = []
    for i, s in enumerate(steps):
        stage, residents, streak = conditions(s, doc)
        rows.append(
            f"  ({q(s['key'])}, {i + 1}, {q(s['label'])}, {stage}, null, null, {residents}, {streak}, "
            f"{q(s['track'])}, {s['step']}, {q(s.get('persona'))}, {q(s.get('community'))}, {q(s.get('landmarkOrder'))}, "
            f"{s['tiles'][0]}, {s['tiles'][1]}, {q(s['site'])})"
        )
    with (HERE / "community_personas.csv").open() as f:
        personas = [(r["code"], r["persona"]) for r in csv.DictReader(f)]
    lines = [
        "-- Module: gamecore — build map seed (requirement.md v1.48 §7.6, §7.9).",
        "-- GENERATED by supabase/data/build_map_seed.py from supabase/data/build_map.json and community_personas.csv. Do not edit by hand.",
        "",
        "insert into gamecore.stage_multipliers (stage, multiplier) values",
        ",\n".join(f"  ({int(k)}, {v})" for k, v in sorted(doc["stageMultipliers"].items(), key=lambda kv: int(kv[0]))),
        "on conflict (stage) do update set multiplier = excluded.multiplier;",
        "",
        "insert into gamecore.land_tiers (stage, min_residents) values",
        ",\n".join(f"  ({i}, {t['minResidents']})" for i, t in enumerate(doc["landTiers"])),
        "on conflict (stage) do update set min_residents = excluded.min_residents;",
        "",
        "-- positions are rewritten below; move the old ones out of the way of the unique constraint",
        "update gamecore.building_types set position = -position;",
        "",
        "insert into gamecore.building_types (key, position, name, stage, lot, grows_from, residents, streak_days,",
        "  track, step, persona, community_code, landmark_order, tiles_w, tiles_d, site) values",
        ",\n".join(rows),
        "on conflict (key) do update set position = excluded.position, name = excluded.name, stage = excluded.stage,",
        "  lot = null, grows_from = null, residents = excluded.residents, streak_days = excluded.streak_days,",
        "  track = excluded.track, step = excluded.step, persona = excluded.persona, community_code = excluded.community_code,",
        "  landmark_order = excluded.landmark_order, tiles_w = excluded.tiles_w, tiles_d = excluded.tiles_d, site = excluded.site;",
        "",
        "-- steps that left the map (pre-launch: their projects were discarded by the previous migration)",
        "delete from gamecore.building_types where key not in (",
        ",\n".join(f"  {q(k)}" for k in keys),
        ");",
        "",
        "insert into gamecore.community_personas (community_id, persona)",
        "select c.id, p.persona from (values",
        ",\n".join(f"  ({q(code)}, {q(persona)})" for code, persona in personas),
        ") as p (code, persona)",
        "join gamecore.communities c on c.code = p.code",
        "on conflict (community_id) do update set persona = excluded.persona;",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    print(f"wrote {out}: {len(steps)} steps, {len(personas)} personas")


if __name__ == "__main__":
    main(sys.argv[1])
