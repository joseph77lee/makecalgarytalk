#!/usr/bin/env python3
"""
Writes the gamecore building-tree seed migration from supabase/data/building_tree.json
(the single source shared with the island plans).

  python3 -I supabase/data/build_tree_seed.py supabase/migrations/<timestamp>_gamecore_building_tree_seed.sql

Rows are upserted, so a later tree change is a new migration generated the same way.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def main(out):
    tree = json.loads((HERE / "building_tree.json").read_text())
    lines = [
        "-- Module: gamecore — building tree seed (requirement.md §7.6).",
        "-- GENERATED by supabase/data/build_tree_seed.py from supabase/data/building_tree.json. Do not edit by hand.",
        "",
        "insert into gamecore.stage_multipliers (stage, multiplier) values",
        ",\n".join(f"  ({int(k)}, {v})" for k, v in sorted(tree["stageMultipliers"].items(), key=lambda kv: int(kv[0]))),
        "on conflict (stage) do update set multiplier = excluded.multiplier;",
        "",
        "insert into gamecore.land_tiers (stage, min_residents) values",
        ",\n".join(f"  ({i}, {t['minResidents']})" for i, t in enumerate(tree["landTiers"])),
        "on conflict (stage) do update set min_residents = excluded.min_residents;",
        "",
        "insert into gamecore.building_types (key, position, name, stage, lot, grows_from, residents, streak_days) values",
        ",\n".join(
            f"  ({q(b['key'])}, {i + 1}, {q(b['name'])}, {b['stage']}, {q(b['lot'])}, {q(b['growsFrom'])}, {b['residents']}, {b['streakDays']})"
            for i, b in enumerate(tree["buildings"])
        ),
        "on conflict (key) do update set position = excluded.position, name = excluded.name, stage = excluded.stage,",
        "  lot = excluded.lot, grows_from = excluded.grows_from, residents = excluded.residents, streak_days = excluded.streak_days;",
        "",
    ]
    reqs = [(b["key"], r) for b in tree["buildings"] for r in b["requires"]]
    if reqs:
        lines += [
            "insert into gamecore.building_requires (building_key, requires_key) values",
            ",\n".join(f"  ({q(a)}, {q(b)})" for a, b in reqs),
            "on conflict do nothing;",
            "",
        ]
    Path(out).write_text("\n".join(lines))
    print(f"wrote {out}: {len(tree['buildings'])} buildings, {len(reqs)} requirements")


if __name__ == "__main__":
    main(sys.argv[1])
