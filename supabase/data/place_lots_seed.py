#!/usr/bin/env python3
"""
Writes the gamecore place-lot seed migration from the stored island plans (requirement.md v1.48
§7.6, §7.8): for every build map step with a lot on a community's island, the land stage at which
that lot has fully risen. The server opens a step only once that land has risen.

  python3 -I supabase/data/place_lots_seed.py supabase/migrations/<timestamp>_gamecore_place_lots_seed.sql

Plans: frontend/public/islands/<CODE>.json (frontend/scripts/island_plans.py). After launch, plan
positions never change; new steps' lots come with a new migration generated the same way.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PLANS = HERE.parent.parent / "frontend" / "public" / "islands"


def q(v):
    return "'" + str(v).replace("'", "''") + "'"


def main(out):
    keys = {s["key"] for s in json.loads((HERE / "build_map.json").read_text())["steps"]}
    rows = []
    for f in sorted(PLANS.glob("*.json")):
        plan = json.loads(f.read_text())
        t = plan["tiles"]
        stage = {(t[i], t[i + 1]): t[i + 2] for i in range(0, len(t), 3)}
        for key, (x, z, w, d, *_rest) in sorted(plan["lots"].items()):
            if key not in keys:
                continue  # Main Street and spare lots are not build map steps
            land = max(stage[(x + i, z + j)] for i in range(w) for j in range(d))
            rows.append(f"  ({q(plan['code'])}, {q(key)}, {land})")
    lines = [
        "-- Module: gamecore — place lots (requirement.md v1.48 §7.6, §7.8).",
        "-- GENERATED by supabase/data/place_lots_seed.py from frontend/public/islands/*.json. Do not edit by hand.",
        "",
        "delete from gamecore.place_lots;",
        "",
        "insert into gamecore.place_lots (community_id, building_key, land_stage)",
        "select c.id, l.building_key, l.land_stage from (values",
        ",\n".join(rows),
        ") as l (code, building_key, land_stage)",
        "join gamecore.communities c on c.code = l.code",
        "on conflict (community_id, building_key) do update set land_stage = excluded.land_stage;",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    print(f"wrote {out}: {len(rows)} lots")


if __name__ == "__main__":
    main(sys.argv[1])
