#!/usr/bin/env python3
"""
Writes the residency boundaries migration from supabase/data/calgary_boundaries.json
(residential community boundaries, the same snapshot the island plans and World Map use).

  python3 -I supabase/data/build_boundaries_sql.py supabase/migrations/<timestamp>_residency_boundaries.sql

Rows are upserted, so a boundary update is a new migration generated the same way.
"""
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def ring_wkt(ring):
    return "(" + ",".join(f"{x} {y}" for x, y in ring) + ")"


def main(out):
    data = json.loads((HERE / "calgary_boundaries.json").read_text())
    rows = []
    for code, rings in sorted(data["communities"].items()):
        polys = ",".join("(" + ring_wkt(r) + ")" for r in rings)
        rows.append(f"  ('{code}', 'MULTIPOLYGON({polys})')")
    lines = [
        "-- Module: residency — residential community boundaries (requirement.md §6.2, §20.2).",
        "-- GENERATED by supabase/data/build_boundaries_sql.py from supabase/data/calgary_boundaries.json. Do not edit by hand.",
        "-- Contains information licensed under the Open Government Licence – City of Calgary.",
        "",
        "insert into residency.boundaries (community_id, area)",
        "select gamecore.community_id_by_code('calgary', v.code), extensions.st_multi(extensions.st_collectionextract(extensions.st_makevalid(extensions.st_geomfromtext(v.wkt, 4326)), 3))",
        "from (values",
        ",\n".join(rows),
        ") as v(code, wkt)",
        "on conflict (community_id) do update set area = excluded.area;",
        "",
    ]
    Path(out).write_text("\n".join(lines))
    print(f"wrote {len(rows)} communities to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
