#!/usr/bin/env python3
"""
Builds supabase/data/calgary_communities.csv from City of Calgary Open Data.

Sources (Open Government Licence – City of Calgary, see docs/data-sources.md):
  - Community District Boundaries (surr-xmvs): name, code, class, sector
  - 2021 Federal Census Population and Dwellings by Community (f9wk-wej9)
  - Historical Community Populations (jtpc-xgsh): fallback (latest civic census year)

Only residential communities are game communities. Run:
  python3 supabase/data/build_communities.py
then regenerate the seed migration with --sql.
"""
import csv
import json
import re
import sys
import urllib.request
from pathlib import Path

HERE = Path(__file__).resolve().parent
API = "https://data.calgary.ca/resource/{id}.json?$limit=50000"


def fetch(dataset_id, select=None):
    url = API.format(id=dataset_id) + (f"&$select={select}" if select else "")
    with urllib.request.urlopen(url, timeout=60) as r:
        return json.load(r)


SMALL = {"of", "and", "the"}
# Names the simple rules get wrong (official spelling).
NAME_OVERRIDES = {"MACEWAN GLEN": "MacEwan Glen"}


def display_name(official):
    """'MCKENZIE TOWNE' -> 'McKenzie Towne'. Operator can override names later."""
    if official in NAME_OVERRIDES:
        return NAME_OVERRIDES[official]
    words = []
    for i, w in enumerate(official.lower().split()):
        if i > 0 and w in SMALL:
            words.append(w)
            continue
        for sep in ("-", "/"):
            w = sep.join(p[:1].upper() + p[1:] for p in w.split(sep))
        w = re.sub(r"^Mc([a-z])", lambda m: "Mc" + m.group(1).upper(), w)
        words.append(w)
    return " ".join(words)


def build_csv():
    districts = fetch("surr-xmvs", "name,comm_code,class,sector")
    fed = {r["community_code"]: r for r in fetch("f9wk-wej9", "community_code,total_pop_household")}
    hist = {}
    for r in fetch("jtpc-xgsh", "comm_code,census_year,population"):
        if not r.get("comm_code") or not r.get("census_year") or r.get("population") in (None, ""):
            continue  # some historical rows have no community code
        y = int(r["census_year"])
        if r["comm_code"] not in hist or y > hist[r["comm_code"]][0]:
            hist[r["comm_code"]] = (y, int(float(r["population"])))

    rows = []
    for d in districts:
        if d.get("class") != "Residential":
            continue
        code = d["comm_code"]
        pop, year = None, None
        if code in fed and fed[code].get("total_pop_household") not in (None, ""):
            pop, year = int(float(fed[code]["total_pop_household"])), 2021
        elif code in hist and hist[code][1] > 0:
            year, pop = hist[code]
        rows.append({
            "code": code,
            "official_name": d["name"],
            "name": display_name(d["name"]),
            "sector": (d.get("sector") or "").title(),
            "population": "" if pop is None else pop,
            "population_year": "" if year is None else year,
        })
    rows.sort(key=lambda r: r["code"])
    with open(HERE / "calgary_communities.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()), lineterminator="\n")
        w.writeheader()
        w.writerows(rows)
    print(f"wrote {len(rows)} communities")


def q(v):
    return "null" if v in ("", None) else "'" + str(v).replace("'", "''") + "'"


def build_sql(out):
    with open(HERE / "calgary_communities.csv") as f:
        rows = list(csv.DictReader(f))
    lines = [
        "-- Module: gamecore — Calgary communities (reference data).",
        "-- GENERATED by supabase/data/build_communities.py --sql from supabase/data/calgary_communities.csv.",
        "-- Contains information licensed under the Open Government Licence – City of Calgary.",
        "",
        "insert into gamecore.communities (city, code, official_name, name, sector, population, population_year) values",
    ]
    values = [
        f"  ('calgary', {q(r['code'])}, {q(r['official_name'])}, {q(r['name'])}, {q(r['sector'])}, "
        f"{r['population'] or 'null'}, {r['population_year'] or 'null'})"
        for r in rows
    ]
    lines.append(",\n".join(values))
    lines.append("on conflict (city, code) do nothing;")
    Path(out).write_text("\n".join(lines) + "\n")
    print(f"wrote {out} ({len(rows)} rows)")


if __name__ == "__main__":
    if "--sql" in sys.argv:
        build_sql(sys.argv[sys.argv.index("--sql") + 1])
    else:
        build_csv()
