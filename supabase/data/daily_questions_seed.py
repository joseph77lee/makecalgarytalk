#!/usr/bin/env python3
"""
Writes the questions seed migration from supabase/data/daily_questions.csv
(requirement.md v1.49 §14.1).

  python3 -I supabase/data/daily_questions_seed.py supabase/migrations/<timestamp>_questions_seed.sql

Rows are upserted by id. Questions no longer in the file are deleted only when they were never
shown (questions.days references them), so a later change is a new migration generated the same
way. The writing rules are checked here and again by supabase/tests/database/questions_rules.test.sql.
"""
import csv
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEASONS = {"winter", "spring", "summer", "fall", "year-round"}
CATEGORIES = {"weather", "neighbourhood", "food", "pride", "sports", "daily", "events"}
MAX_CHOICE = 32


def q(v):
    return "null" if v is None else "'" + str(v).replace("'", "''") + "'"


def is_flag(emoji):
    return any(0x1F1E6 <= ord(ch) <= 0x1F1FF for ch in emoji)


def rows():
    out, problems = [], []
    with open(HERE / "daily_questions.csv", encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            choices = []
            for i in range(1, 5):
                e, t = (r.get(f"opt{i}_emoji") or "").strip(), (r.get(f"opt{i}_text") or "").strip()
                if e or t:
                    choices.append({"emoji": e, "text": t})
            qid = r["id"].strip()
            if r["season"] not in SEASONS:
                problems.append(f"{qid}: season {r['season']!r}")
            if r["category"] not in CATEGORIES:
                problems.append(f"{qid}: category {r['category']!r}")
            if not 2 <= len(choices) <= 4:
                problems.append(f"{qid}: {len(choices)} choices")
            if len({c["emoji"] for c in choices}) != len(choices) or any(not c["emoji"] or not c["text"] for c in choices):
                problems.append(f"{qid}: choices need a distinct emoji and a text")
            for c in choices:
                if len(c["text"]) > MAX_CHOICE:
                    problems.append(f"{qid}: choice longer than {MAX_CHOICE}: {c['text']!r}")
                if is_flag(c["emoji"]):
                    problems.append(f"{qid}: flag emoji")
            out.append((qid, r["category"], r["season"], r["situation"].strip() or None, r["question"].strip(), choices))
    if len({r[0] for r in out}) != len(out):
        problems.append("duplicate ids")
    if problems:
        sys.exit("daily_questions.csv:\n  " + "\n  ".join(problems))
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    data = rows()
    lines = [
        "-- Module: questions — seed generated by supabase/data/daily_questions_seed.py from",
        "-- supabase/data/daily_questions.csv (requirement.md v1.49 §14.1). Do not edit by hand.",
        "",
        "insert into questions.questions (id, category, season, situation, question, choices) values",
    ]
    values = [
        f"  ({q(i)}, {q(c)}, {q(s)}, {q(sit)}, {q(text)}, {q(json.dumps(ch, ensure_ascii=False))}::jsonb)"
        for i, c, s, sit, text, ch in data
    ]
    lines.append(",\n".join(values))
    lines.append("on conflict (id) do update set category = excluded.category, season = excluded.season,")
    lines.append("  situation = excluded.situation, question = excluded.question, choices = excluded.choices;")
    lines.append("")
    ids = ", ".join(q(r[0]) for r in data)
    lines.append(f"delete from questions.questions q where q.id not in ({ids})")
    lines.append("  and not exists (select 1 from questions.days d where d.question_id = q.id);")
    Path(sys.argv[1]).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(data)} questions → {sys.argv[1]}")


if __name__ == "__main__":
    main()
