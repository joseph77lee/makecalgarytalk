"""Downloads the Polyfork models the game uses and writes their credits (requirement.md v1.45 §19.2).

Reads docs/polyfork-picks.json (the 82 picks in 12 groups; a model can sit in more than one group)
and, for every model id:
  - downloads https://polyfork.dev/cdn/<id>.glb to public/models/pf/<id>.glb (skips files already there;
    pass --force to download again). Only the GLB mesh files are hosted, never Polyfork's .mjs code.
  - reads the credit from the file's own glTF `asset.copyright` (falls back to "<title> by Polyfork
    (<page>), CC BY 4.0" when a file carries none, e.g. the rigged animals)
  - writes public/models/pf/CREDITS.md and the Polyfork list in public/credits.html (between the
    <!-- polyfork:start --> and <!-- polyfork:end --> markers)

Rerun after changing the picks:  python3 -I scripts/polyfork_models.py  (from frontend/)
"""
import html
import json
import struct
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PICKS = ROOT.parent / 'docs' / 'polyfork-picks.json'
OUT_DIR = ROOT / 'public' / 'models' / 'pf'
CREDITS_MD = OUT_DIR / 'CREDITS.md'
CREDITS_HTML = ROOT / 'public' / 'credits.html'
CDN = 'https://polyfork.dev/cdn/{id}.glb'
PAGE = 'https://polyfork.dev/asset/{id}'
START = '<!-- polyfork:start -->'
END = '<!-- polyfork:end -->'


def glb_json(data: bytes) -> dict:
    """The glTF JSON chunk of a GLB file (the binary chunk is never parsed)."""
    if data[:4] != b'glTF':
        raise ValueError('not a GLB file')
    length, kind = struct.unpack('<II', data[12:20])
    if kind != 0x4E4F534A:  # 'JSON'
        raise ValueError('first chunk is not JSON')
    return json.loads(data[20:20 + length])


def download(model_id: str, dest: Path) -> None:
    req = urllib.request.Request(CDN.format(id=model_id), headers={'User-Agent': 'polyfork-models-script'})
    with urllib.request.urlopen(req, timeout=60) as r:
        data = r.read()
    glb_json(data)  # refuse anything that is not a GLB
    dest.write_bytes(data)


def main() -> None:
    force = '--force' in sys.argv
    groups = json.loads(PICKS.read_text())
    models: dict[str, str] = {}
    for g in groups:
        for item in g['items']:
            models.setdefault(item['id'], item['title'])
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    credits: list[tuple[str, str, str]] = []
    for model_id, title in sorted(models.items()):
        dest = OUT_DIR / f'{model_id}.glb'
        if force or not dest.exists():
            print(f'download {model_id}')
            download(model_id, dest)
        meta = glb_json(dest.read_bytes()).get('asset', {})
        credit = meta.get('copyright') or f'{title} by Polyfork ({PAGE.format(id=model_id)}), CC BY 4.0'
        credits.append((model_id, title, credit))

    lines = [
        '# Polyfork low-poly models (CC BY 4.0)',
        '',
        'Generated by scripts/polyfork_models.py from docs/polyfork-picks.json. Each file is used under',
        'CC BY 4.0 with the credit below (from the file itself where it carries one). Colours are changed',
        'in the game (pastel repaint).',
        '',
    ]
    lines += [f'- {mid}.glb: {credit}' for mid, _, credit in credits]
    CREDITS_MD.write_text('\n'.join(lines) + '\n')

    items = '\n'.join(
        f'<li><a href="{PAGE.format(id=mid)}">{html.escape(title)}</a></li>' for mid, title, _ in credits
    )
    block = (
        f'{START}\n<h2>3D models</h2>\n'
        '<p>Houses, buildings, trees, cars, people and animals are low-poly models by '
        '<a href="https://polyfork.dev">Polyfork</a>, licensed under '
        '<a href="https://creativecommons.org/licenses/by/4.0/">CC BY 4.0</a>. Their colours were changed '
        'to match the game.</p>\n'
        f'<ul class="columns">\n{items}\n</ul>\n{END}'
    )
    page = CREDITS_HTML.read_text()
    if START in page:
        before, rest = page.split(START, 1)
        page = before + block + rest.split(END, 1)[1]
    else:
        page = page.replace('<h2>Software</h2>', f'{block}\n\n<h2>Software</h2>', 1)
    CREDITS_HTML.write_text(page)
    print(f'{len(credits)} models, credits written')


if __name__ == '__main__':
    main()
